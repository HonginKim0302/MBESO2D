function P = prepare_figure8_data(sourceRoot, outputDir)
%PREPARE_FIGURE1_DATA Extract real saved arrays; no FE or optimization is run.
% sourceRoot is the Revision5 MBESO-MATLAB-v1.0.0 folder. This preparation
% function requires the archives; reproduce_figure1 uses only local data.
sourceFolder=fileparts(mfilename('fullpath'));
oldPath=path; restorePath=onCleanup(@()path(oldPath)); %#ok<NASGU>
addpath(fileparts(sourceFolder),'-begin');
materialPalette=mbeso_reproduction_palette;
here=outputDir;
initialPath = fullfile(sourceRoot,'initial10','cantilever','full_history.mat');
fullPath = fullfile(sourceRoot,'zero_history','cantilever_eps_0','full_history.mat');
initial = load(initialPath,'data'); initial = initial.data;
full = load(fullPath,'data'); full = full.data;
assert(initial.cfg.nely == 60 && initial.cfg.nelx == 100);
assert(full.n_updates >= 214 && full.first_stop == 214);
checks = cell(0,4);
checks(end+1,:) = {'state0_to10_phase_matches_initial_archive',double(~isequal(initial.phase(:,1:11),full.phase(:,1:11))),0,[]};
fields = {'trace_raw','trace_filtered','eta_raw','eta_spatial','eta_history','vm_center','sig1','sig2'};
for j = 1:numel(fields)
    f = fields{j}; a = double(initial.(f)(:,1:10)); b = double(full.(f)(:,1:10));
    checks(end+1,:) = {['initial10_prefix_' f],max(abs(a(:)-b(:))),0,[]}; %#ok<AGROW>
end
checks(end+1,:) = {'response_C_state0_to10_matches_initial_archive',max(abs(initial.C(1:11)-full.C(1:11))),0,[]};
checks(end+1,:) = {'driving_trace_at_update1_to11_equals_FE_state0_to10', ...
    max(abs(double(full.trace_raw(:,1:11))-double(full.state_trace(:,1:11))),[],'all'),0,[]};
checks(end+1,:) = {'first_update_temporal_score_equals_spatial_score', ...
    max(abs(full.eta_history(:,1)-full.eta_spatial(:,1))),0,[]};
actualAverage = 0.5*(full.eta_spatial(:,1:10)+full.eta_spatial(:,2:11));
checks(end+1,:) = {'later_temporal_score_averages_consecutive_spatial_fields', ...
    max(abs(actualAverage-full.eta_history(:,2:11)),[],'all'),0,[]};
checks(end+1,:) = {'initial_cutoff_is_undefined_not_zero',double(~isnan(full.cutoff(1))),0,[]};
checks(end+1,:) = {'phase_state10_is_actual_saved_column11',double(~isequal(initial.phase(:,11),full.phase(:,11))),0,[]};
checks(end+1,:) = {'phase_state10_uses_valid_material_ids',double(~all(ismember(full.phase(:,11),[0 1 2]))),0,[]};

P = struct();
P.description = 'Stored cantilever baseline arrays; no reconstructed curves or screenshot digitization.';
P.response = struct('state_iteration',(0:214)', ...
    'Vk',full.scheduled_volume(1:215),'nk',full.nk(1:215), ...
    'V1',full.V1(1:215),'C_Nmm',full.C(1:215));
P.response.marked_states = (0:10:210)';
P.local = struct('state_iteration',(0:10)','decision_update',(1:11)', ...
    'element_primary',974,'element_boundary',5829, ...
    'trace_raw_974_MPa',full.trace_raw(974,1:11)', ...
    'trace_filtered_974_MPa',full.trace_filtered(974,1:11)', ...
    'eta_raw_974',full.eta_raw(974,1:11)', ...
    'eta_spatial_974',full.eta_spatial(974,1:11)', ...
    'eta_temporal_974',full.eta_history(974,1:11)', ...
    'selection_cutoff',full.cutoff(2:12), ...
    'eta_temporal_5829',full.eta_history(5829,1:11)', ...
    'nk_before_decision',full.nk(1:11),'nk_used_for_decision',full.nk(2:12));
P.material = struct('state_iteration',10,'nely',60,'nelx',100, ...
    'phase',reshape(full.phase(:,11),60,100), ...
    'element_ids',[974;5829],'rows',[14;9],'columns',[17;98], ...
    'colors',materialPalette.map);
for j = 1:2
    [rr,cc] = ind2sub([60,100],P.material.element_ids(j));
    checks(end+1,:) = {sprintf('element_%d_grid_location',P.material.element_ids(j)), ...
        abs(rr-P.material.rows(j))+abs(cc-P.material.columns(j)),0,[]}; %#ok<AGROW>
end
P.index_semantics = struct( ...
    'panel_a','Physical response state k=0:214; nk is the value stored at each state.', ...
    'panels_b_c','Stored input states s=0:10; plot only s=0:9 at decision updates k=1:10.', ...
    'panel_c_nk','eta uses nk after its update, namely full.nk(s+2), not nk before the decision.', ...
    'panel_e','Actual material phase after update10, MATLAB phase(:,11).', ...
    'comparison_with_old_figure','The plotting helper selects the first10 original inputs; stored update11 is retained as archival data but not plotted.', ...
    'cutoff','No invented initialization cutoff. At plotted update1, the real outgoing decision1 cutoff from FE state0 is shown.');
P.units = struct('trace','MPa','eta_and_cutoff','dimensionless','C','N mm','volume_fractions','fraction of all 6000 elements');
P.canvas_mm = [151.1 169.9];
P.reference_pixels = [893 1003];
P.axes_rect_pixels_top_origin = [94 50 700 208;94 397 326 240;530 397 326 240;573 799 248 149];
P.panel_names = {'a','b','c','e'};
P.font_name = 'Times New Roman'; P.font_size_pt = 9; P.label_font_size_pt = 9.5;
P.no_exclusion_region = true;
P.events = struct('panel',{'b','c','c'},'state_iteration',{6,1,4}, ...
    'decision_update',{7,2,5},'field',{'trace_filtered_974_MPa','eta_temporal_5829','eta_temporal_974'}, ...
    'value',{P.local.trace_filtered_974_MPa(7),P.local.eta_temporal_5829(2),P.local.eta_temporal_974(5)});

for j = 1:size(checks,1), checks{j,4} = checks{j,2} <= checks{j,3}; end
assert(all(cell2mat(checks(:,4))),'Saved-array verification failed.');
dataDir = fullfile(here,'data'); if ~isfolder(dataDir), mkdir(dataDir); end
save(fullfile(dataDir,'plot_inputs.mat'),'P','-v7');
write_numeric(fullfile(dataDir,'panel_a_response.csv'), ...
    {'state_iteration','Vk_scheduled','nk_stored','V1_over_all_elements','C_Nmm','marker_shown'}, ...
    [P.response.state_iteration,P.response.Vk,P.response.nk,P.response.V1,P.response.C_Nmm,ismember(P.response.state_iteration,P.response.marked_states)]);
write_numeric(fullfile(dataDir,'panels_b_c_local_fields.csv'), ...
    {'state_iteration','decision_update','trace_raw_974_MPa','trace_filtered_974_MPa', ...
    'eta_raw_974','eta_spatial_974','eta_temporal_974','selection_cutoff','eta_temporal_5829','nk_before_decision','nk_used_for_decision'}, ...
    [P.local.state_iteration,P.local.decision_update,P.local.trace_raw_974_MPa,P.local.trace_filtered_974_MPa, ...
    P.local.eta_raw_974,P.local.eta_spatial_974,P.local.eta_temporal_974,P.local.selection_cutoff,P.local.eta_temporal_5829, ...
    P.local.nk_before_decision,P.local.nk_used_for_decision]);
[rows,cols] = ind2sub([60,100],(1:6000)');
write_numeric(fullfile(dataDir,'panel_e_material_state10.csv'), ...
    {'element_id','row_from_top','column_from_left','x_mm','y_mm_from_top','phase_id'}, ...
    [(1:6000)',rows,cols,(cols-0.5)*10,(rows-0.5)*10,double(P.material.phase(:))]);
write_numeric(fullfile(dataDir,'panel_e_selected_elements.csv'), ...
    {'element_id','row_from_top','column_from_left','phase_at_state10'}, ...
    [P.material.element_ids,P.material.rows,P.material.columns,double(P.material.phase(P.material.element_ids))]);
fid=fopen(fullfile(dataDir,'event_annotations.csv'),'w','n','UTF-8'); guard=onCleanup(@()fclose(fid));
fprintf(fid,'panel,state_iteration,decision_update,field,actual_saved_value\n');
for j=1:numel(P.events),e=P.events(j);fprintf(fid,'%s,%d,%d,%s,%.17g\n',e.panel,e.state_iteration,e.decision_update,e.field,e.value);end
clear guard;
fid = fopen(fullfile(dataDir,'verification_checks.csv'),'w','n','UTF-8'); guard = onCleanup(@()fclose(fid));
fprintf(fid,'check_id,max_absolute_difference,tolerance,passed\n');
for j = 1:size(checks,1), fprintf(fid,'%s,%.17g,%.17g,%d\n',checks{j,:}); end
clear guard;
provenance = struct('preparation_function','prepare_figure1_data.m','source_root',sourceRoot, ...
    'sources',struct('role',{},'absolute_path',{},'relative_path',{},'sha256',{}), ...
    'index_semantics',P.index_semantics,'checks_passed',all(cell2mat(checks(:,4))));
sources = {initialPath,'initial10_prefix_crosscheck';fullPath,'full_baseline_and_update11'};
for j = 1:size(sources,1)
    provenance.sources(j) = struct('role',sources{j,2},'absolute_path',sources{j,1}, ...
        'relative_path',strrep(sources{j,1},[sourceRoot filesep],''),'sha256',sha256_file(sources{j,1}));
end
write_json(fullfile(dataDir,'provenance.json'),provenance);
write_json(fullfile(dataDir,'preparation_status.json'),struct('passed',true,'saved_array_checks',size(checks,1), ...
    'actual_response_states',215,'actual_local_FE_states',11,'actual_decision_updates',11, ...
    'material_phase_state',10,'no_FE_or_optimization_executed',true));
fprintf('Figure1 preparation complete: %s\n',dataDir);
end

function write_numeric(path,headers,A)
fid=fopen(path,'w','n','UTF-8'); assert(fid>=0); guard=onCleanup(@()fclose(fid));
fprintf(fid,'%s\n',strjoin(headers,','));
fmt=[repmat('%.17g,',1,size(A,2)-1),'%.17g\n']; fprintf(fid,fmt,A');
end
function hash = sha256_file(path)
fid=fopen(path,'rb'); guard=onCleanup(@()fclose(fid));
md=java.security.MessageDigest.getInstance('SHA-256');
while ~feof(fid), bytes=fread(fid,1024*1024,'*uint8'); md.update(bytes); end
hash=lower(reshape(dec2hex(typecast(md.digest(),'uint8'),2)',1,[]));
end
function write_json(path,value)
fid=fopen(path,'w','n','UTF-8'); guard=onCleanup(@()fclose(fid));
fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));
end
