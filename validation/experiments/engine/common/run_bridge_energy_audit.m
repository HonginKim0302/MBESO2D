function audit = run_bridge_energy_audit(result,cfg,outDir)
% Independent frozen-layout FE/load/energy audit; also accepts cantilevers.
if ~exist(outDir,'dir'), mkdir(outDir); end
fe=verification_independent_fe(result,cfg);
K=fe.K; F=fe.F; U=fe.U; free=fe.free_dofs;
E_force=.5*full(F'*U); E_stiffness=.5*full(U'*K*U);
E_element=sum(fe.element_energy_Nmm);
source_E_force=.5*full(F'*fe.U_source);
source_E_stiffness=.5*full(fe.U_source'*K*fe.U_source);
reactions=zeros(size(F)); reactions(fe.fixed_dofs)=fe.reaction(fe.fixed_dofs);
balance=F+reactions;
moment=sum(fe.node_xy_mm(:,1).*balance(2:2:end)-fe.node_xy_mm(:,2).*balance(1:2:end));
force_scale=max(norm(F,1),1);
moment_scale=max(force_scale*max(fe.node_xy_mm(:)),1);
Uq=zeros(size(U)); Ug=Uq;
split=K(free,free)\[fe.Fq(free),fe.Fg(free)];
Uq(free)=split(:,1); Ug(free)=split(:,2);
A=.5*full(fe.Fq'*Uq); B=full(fe.Fq'*Ug); D=.5*full(fe.Fg'*Ug);
relative=@(a,b) abs(a-b)/max(abs(b),eps);
solid=result.mi_map~=0;
stress_relative=norm(fe.center_vm(solid)-result.response.sigvm(solid))/max(norm(result.response.sigvm(solid)),eps);
rows={ ...
    'external_vertical_load',full(sum(fe.Fq(2:2:end))),'N'; ...
    'self_weight_vertical_load',full(sum(fe.Fg(2:2:end))),'N'; ...
    'total_vertical_load',full(sum(F(2:2:end))),'N'; ...
    'physical_mass',fe.mass_kg,'kg'; ...
    'energy_force',E_force,'N mm'; ...
    'energy_stiffness',E_stiffness,'N mm'; ...
    'energy_element',E_element,'N mm'; ...
    'source_reported_energy',result.compliance,'N mm'; ...
    'source_force_energy',source_E_force,'N mm'; ...
    'source_stiffness_energy',source_E_stiffness,'N mm'; ...
    'relative_force_stiffness_energy_error',relative(E_stiffness,E_force),'1'; ...
    'relative_force_element_energy_error',relative(E_element,E_force),'1'; ...
    'relative_source_energy_error',relative(result.compliance,E_force),'1'; ...
    'relative_source_displacement_error',norm(fe.U_source-U)/max(norm(U),eps),'1'; ...
    'relative_source_solid_center_vm_error',stress_relative,'1'; ...
    'relative_free_equilibrium_residual',norm(fe.reaction(free))/max(norm(F(free)),eps),'1'; ...
    'relative_source_free_equilibrium_residual',norm(fe.source_residual(free))/max(norm(F(free)),eps),'1'; ...
    'horizontal_force_balance',full(sum(balance(1:2:end))),'N'; ...
    'vertical_force_balance',full(sum(balance(2:2:end))),'N'; ...
    'moment_balance',full(moment),'N mm'; ...
    'relative_horizontal_force_balance',abs(full(sum(balance(1:2:end))))/force_scale,'1'; ...
    'relative_vertical_force_balance',abs(full(sum(balance(2:2:end))))/force_scale,'1'; ...
    'relative_moment_balance',abs(full(moment))/moment_scale,'1'; ...
    'relative_energy_decomposition_error',relative(A+B+D,E_force),'1'; ...
    'relative_reciprocity_error',abs(full(fe.Fq'*Ug-fe.Fg'*Uq))/max(abs(B),1),'1'};
metrics=cell2table(rows,'VariableNames',{'metric','value','unit'});
verification_write_table(metrics,fullfile(outDir,'energy_audit.csv'));
decomposition=table({'external_only';'cross';'self_weight_only';'total'}, ...
    [A;B;D;A+B+D],[A;B;D;A+B+D]/1000, ...
    'VariableNames',{'component','energy_Nmm','energy_Nm'});
verification_write_table(decomposition,fullfile(outDir,'energy_decomposition.csv'));
% K scales with thickness; gravity scales with thickness; external F is fixed.
lambda=[.5;1;2]; computed=zeros(3,1); predicted=A./lambda+B+D.*lambda;
for j=1:3
    Fl=fe.Fq+lambda(j)*fe.Fg;
    Ul=zeros(size(U)); Ul(free)=(lambda(j)*K(free,free))\Fl(free);
    computed(j)=.5*full(Fl'*Ul);
end
thickness=table(lambda,computed,predicted,abs(computed-predicted)./max(abs(predicted),eps), ...
    'VariableNames',{'lambda','computed_energy_Nmm','predicted_energy_Nmm','relative_error'});
verification_write_table(thickness,fullfile(outDir,'thickness_scaling.csv'));
check_names={'independent_energy_identity';'source_energy';'source_displacement'; ...
    'source_solid_stress';'free_equilibrium';'source_free_equilibrium'; ...
    'force_balance';'moment_balance';'energy_decomposition';'thickness_scaling'};
check_errors=[max(relative(E_stiffness,E_force),relative(E_element,E_force)); ...
    relative(result.compliance,E_force);norm(fe.U_source-U)/max(norm(U),eps); ...
    stress_relative;norm(fe.reaction(free))/max(norm(F(free)),eps); ...
    norm(fe.source_residual(free))/max(norm(F(free)),eps); ...
    max(abs([full(sum(balance(1:2:end))),full(sum(balance(2:2:end)))]))/force_scale; ...
    abs(moment)/moment_scale;relative(A+B+D,E_force);max(thickness.relative_error)];
% Ersatz systems can be ill-conditioned. Displacement tolerance is explicitly
% looser than energy/residual tolerance; no rounding is used in these checks.
tolerances=[1e-7;1e-6;1e-5;1e-5;1e-7;1e-7;1e-7;1e-7;1e-7;1e-7];
checks=table(check_names,check_errors,tolerances,check_errors<=tolerances, ...
    'VariableNames',{'check','relative_error','tolerance','passed'});
verification_write_table(checks,fullfile(outDir,'energy_checks.csv'));
audit=struct('case_id',cfg.case_id,'metrics',metrics,'decomposition',decomposition, ...
    'thickness',thickness,'checks',checks,'passed',all(checks.passed), ...
    'energy_definition','0.5 F^T U (strain energy); N mm', ...
    'notes','Independent Gauss-integrated Q4 assembly; frozen material layout; no external Abaqus rerun.', ...
    'fe',fe,'Uq',Uq,'Ug',Ug);
save(fullfile(outDir,'independent_fe_audit.mat'),'audit','cfg','-v7.3');
end
