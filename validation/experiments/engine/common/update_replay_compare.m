function row=update_replay_compare(snapshot,predicted,caseID)
% Comparison tolerances are declared before execution, not fitted to results.
q=snapshot.production;tol=1e-12;
relative=@(x,y)norm(double(x(:))-double(y(:)))/max(norm(double(y(:))),eps);
row=struct('case_id',string(caseID),'iteration',snapshot.iteration, ...
    'input_state_iteration',snapshot.iteration-1,'relative_tolerance',tol, ...
    'nk_relative_error',relative(predicted.nk,q.nk), ...
    'eta_raw_relative_error',relative(predicted.eta_raw,q.eta_raw), ...
    'eta_spatial_relative_error',relative(predicted.eta_spatial,q.eta_spatial), ...
    'eta_history_relative_error',relative(predicted.eta_history,q.eta_history), ...
    'trace_filtered_relative_error',relative(predicted.sigma_filtered,q.sigma_filtered), ...
    'eta_history_max_absolute_error',max(abs(predicted.eta_history(:)-q.eta_history(:))), ...
    'trace_filtered_max_absolute_error',max(abs(predicted.sigma_filtered(:)-q.sigma_filtered(:))), ...
    'target_keep_production',q.target_keep,'target_keep_independent',predicted.target_keep, ...
    'effective_keep_production',q.effective_keep,'effective_keep_independent',predicted.effective_keep, ...
    'actual_keep_production',nnz(q.keep_mask),'actual_keep_independent',nnz(predicted.keep_mask), ...
    'keep_mask_mismatches',nnz(predicted.keep_mask~=q.keep_mask), ...
    'material_map_mismatches',nnz(predicted.mi_map~=q.mi_map), ...
    'density_map_mismatches',nnz(predicted.x~=q.x), ...
    'cutoff_production',q.cutoff,'cutoff_independent',predicted.cutoff, ...
    'volume_next_production',q.volume_next,'volume_next_independent',predicted.volume_next, ...
    'selection_epsilon',predicted.selection_epsilon,'exact_cutoff_ties',predicted.exact_cutoff_ties, ...
    'rank_margin',predicted.rank_margin,'minimum_filtered_trace_abs',min(abs(predicted.sigma_filtered(:))), ...
    'filtered_trace_sign_mismatches',nnz((predicted.sigma_filtered>=0)~=(q.sigma_filtered>=0)), ...
    'fixed_solid_violations',nnz(snapshot.inputs.fixed_solid_mask & ~predicted.keep_mask), ...
    'forced_void_violations',nnz(~snapshot.inputs.design_mask & ~snapshot.inputs.fixed_solid_mask & predicted.keep_mask), ...
    'passed',false);
errors=[row.nk_relative_error,row.eta_raw_relative_error,row.eta_spatial_relative_error, ...
    row.eta_history_relative_error,row.trace_filtered_relative_error];
row.passed=all(errors<=tol) && row.target_keep_production==row.target_keep_independent && ...
    row.effective_keep_production==row.effective_keep_independent && ...
    row.volume_next_production==row.volume_next_independent && ...
    row.keep_mask_mismatches==0 && row.material_map_mismatches==0 && row.density_map_mismatches==0 && ...
    row.fixed_solid_violations==0 && row.forced_void_violations==0;
end
