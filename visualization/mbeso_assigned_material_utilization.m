function utilization = mbeso_assigned_material_utilization(result)
%MBESO_ASSIGNED_MATERIAL_UTILIZATION Utilization of the assigned material.
% Uses element-center response.sigvm and the strength selected by mi_map.
% percent is nonnegative; signed_percent is positive for M1 and negative for
% M2. Void entries are NaN. The display sign denotes material identity, not
% the sign of the raw or filtered principal-stress sum. Optimization eta and
% the continuation factor n_k are not used.

if ~isstruct(result) || ~isscalar(result) || ...
        ~all(isfield(result, {'x', 'mi_map', 'materials', 'settings', 'response'}))
    error('MBESO2D:AssignedUtilization:InvalidResult', ...
        'A scalar result with x, mi_map, materials, settings, and response is required.');
end
if ~isnumeric(result.x) || ~isreal(result.x) || ~ismatrix(result.x) || ...
        isempty(result.x) || any(~isfinite(result.x(:))) || any(result.x(:) < 0)
    error('MBESO2D:AssignedUtilization:InvalidDensity', ...
        'result.x must be a nonempty, finite, nonnegative real matrix.');
end
if ~isstruct(result.settings) || ~isscalar(result.settings) || ...
        ~isfield(result.settings, 'xmin') || ~valid_scalar(result.settings.xmin) || ...
        result.settings.xmin < 0
    error('MBESO2D:AssignedUtilization:InvalidThreshold', ...
        'result.settings.xmin must be a finite nonnegative real scalar.');
end
if ~isnumeric(result.mi_map) || ~isreal(result.mi_map) || ...
        ~isequal(size(result.mi_map), size(result.x)) || ...
        any(~ismember(result.mi_map(:), [0, 1, 2]))
    error('MBESO2D:AssignedUtilization:InvalidMaterialMap', ...
        'result.mi_map must match result.x and contain only material IDs 0, 1, and 2.');
end
solid_mask = result.x > result.settings.xmin;
if any(result.mi_map(solid_mask) == 0)
    error('MBESO2D:AssignedUtilization:UnassignedSolid', ...
        'Every solid element must have assigned material ID 1 or 2.');
end
if ~isstruct(result.materials) || ~isscalar(result.materials) || ...
        ~all(isfield(result.materials, {'sigma_m1', 'sigma_m2'})) || ...
        ~valid_scalar(result.materials.sigma_m1) || result.materials.sigma_m1 <= 0 || ...
        ~valid_scalar(result.materials.sigma_m2) || result.materials.sigma_m2 <= 0
    error('MBESO2D:AssignedUtilization:InvalidStrength', ...
        'Assigned material strengths sigma_m1 and sigma_m2 must be finite positive real scalars.');
end
if ~isstruct(result.response) || ~isscalar(result.response) || ...
        ~isfield(result.response, 'sigvm') || ~isnumeric(result.response.sigvm) || ...
        ~isreal(result.response.sigvm) || ...
        ~isequal(size(result.response.sigvm), size(result.x))
    error('MBESO2D:AssignedUtilization:InvalidStress', ...
        'Element-center result.response.sigvm must be a real matrix matching result.x.');
end
sigvm = double(result.response.sigvm);
if any(~isfinite(sigvm(solid_mask))) || any(sigvm(solid_mask) < 0)
    error('MBESO2D:AssignedUtilization:InvalidStress', ...
        'Element-center von Mises stress must be finite and nonnegative on solid elements.');
end

material_map = result.mi_map;
material_map(~solid_mask) = 0;
tensile_mask = solid_mask & material_map == 1;
compressive_mask = solid_mask & material_map == 2;
percent = NaN(size(result.x));
percent(tensile_mask) = 100 * (sigvm(tensile_mask) / double(result.materials.sigma_m1));
percent(compressive_mask) = 100 * (sigvm(compressive_mask) / double(result.materials.sigma_m2));
if any(~isfinite(percent(solid_mask)))
    error('MBESO2D:AssignedUtilization:InvalidStress', ...
        'Assigned material utilization exceeds the finite numeric range.');
end
signed_percent = percent;
signed_percent(compressive_mask) = -percent(compressive_mask);
[tensile_max_percent, tensile_max_element_index] = material_maximum(percent, tensile_mask);
[compressive_max_percent, compressive_max_element_index] = material_maximum(percent, compressive_mask);
utilization = struct( ...
    'percent', percent, 'signed_percent', signed_percent, ...
    'material_map', material_map, 'solid_mask', solid_mask, ...
    'tensile_mask', tensile_mask, 'compressive_mask', compressive_mask, ...
    'tensile_max_percent', tensile_max_percent, ...
    'compressive_max_percent', compressive_max_percent, ...
    'tensile_max_element_index', tensile_max_element_index, ...
    'compressive_max_element_index', compressive_max_element_index, ...
    'definition', ['100 * element-center von Mises stress / assigned material strength; ' ...
        'M1 uses sigma_m1, M2 uses sigma_m2; display sign +M1/-M2; void excluded.']);
end

function valid = valid_scalar(value)
valid = isnumeric(value) && isreal(value) && isscalar(value) && isfinite(value);
end

function [maximum, element_index] = material_maximum(percent, mask)
indices = find(mask);
if isempty(indices)
    maximum = NaN;
    element_index = NaN;
else
    [maximum, offset] = max(percent(indices));
    element_index = indices(offset);
end
end
